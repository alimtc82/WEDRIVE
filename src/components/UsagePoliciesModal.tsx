export default function UsagePoliciesModal({ role, open, onClose }: { role: Role; open: boolean; onClose: () => void }) {
  useEffect(() => {
    if (!open) return;
    const onKey = (e: KeyboardEvent) => { if (e.key === "Escape") onClose(); };
    document.addEventListener("keydown", onKey);
    const old = document.body.style.overflow;
    document.body.style.overflow = "hidden";
    return () => { document.removeEventListener("keydown", onKey); document.body.style.overflow = old; };
  }, [open, onClose]);

  if (!open) return null;
  const sections = [...COMMON, ...(role === "captain" ? CAPTAIN : CUSTOMER)];

  return (
    <div className="policyOverlay" role="presentation" onMouseDown={(e) => { if (e.target === e.currentTarget) onClose(); }}>
      <section className="policyModal" role="dialog" aria-modal="true" aria-labelledby="policy-title" dir="rtl">
        <header className="policyHead">
          <div>
            <span>الإصدار {TERMS_VERSION}</span>
            <h2 id="policy-title">سياسات استخدام كابتن بنها — {role === "captain" ? "الكابتن" : "العميل"}</h2>
            <p>يرجى قراءة البنود كاملة قبل إنشاء الحساب.</p>
          </div>
          <button type="button" onClick={onClose} aria-label="إغلاق">×</button>
        </header>
        <div className="policyBody">
          <div className="policyImportant">
            بإنشاء الحساب والموافقة، تقر بأنك قرأت هذه السياسات وفهمتها ووافقت عليها إلكترونيًا. هذه الصياغة لا تلغي أي حق أو مسؤولية لا يجوز قانونًا التنازل عنها.
          </div>
          {sections.map((s) => (
            <article key={s.title}>
              <h3>{s.title}</h3>
              {s.body.map((p, i) => <p key={i}>{p}</p>)}
            </article>
          ))}
          <article>
            <h3>إقرار نهائي</h3>
            <p>أقر بأنني قرأت وفهمت البنود السابقة، وأن موافقتي الإلكترونية صادرة بإرادتي، وأن البيانات التي قدمتها صحيحة، وألتزم باستخدام المنصة بصورة مشروعة وآمنة.</p>
          </article>
        </div>
        <footer className="policyFoot">
          <button type="button" onClick={onClose}>فهمت — إغلاق</button>
        </footer>
      </section>
    </div>
  );
}
